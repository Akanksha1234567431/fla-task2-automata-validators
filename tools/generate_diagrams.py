#!/usr/bin/env python3
"""Regenerate every diagram (diagrams/*.dot, *.png, *.svg) and docs/design_stats.md.

    python tools/generate_diagrams.py

Requires Graphviz (`dot`) on PATH.  The DOT sources are always written; images are
rendered only if `dot` is available.
"""
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from validators import email, password, pin  # noqa: E402

OUT = ROOT / "diagrams"
DOCS = ROOT / "docs"
OUT.mkdir(exist_ok=True)
DOCS.mkdir(exist_ok=True)

DIAGRAMS = {
    "pin_dfa": pin.PIN_DFA.to_dot("Fig. 1  ATM PIN DFA   L = D^4", pin.LEGEND),
    "pin_retry_dfa": pin.RETRY_DFA.to_dot("Fig. 2  ATM retry limiter (events from the bank)", pin.RETRY_LEGEND),
    "email_nfa": email.EMAIL_NFA.to_dot("Fig. 3  E-mail format NFA (9 states)", email.LEGEND),
    "email_dfa_min": email.EMAIL_DFA.to_dot("Fig. 4  E-mail format DFA - minimal (9 states)", email.LEGEND),
    "password_mini_dfa": password.MINI_DFA.to_dot(
        "Fig. 5  Scaled-down password DFA: length 3-4, >=1 letter, >=1 digit", password.MINI_LEGEND),
    "password_length_dfa": password.length_dfa(8, 16, password.ALPHABET).to_dot(
        "Fig. 6a  Rule automaton: 8 <= length <= 16 (any class)", {"any symbol": "U, L, D, S or X"}),
    "password_contains_dfa": password.contains_dfa("U", password.ALPHABET).to_dot(
        "Fig. 6b  Rule automaton: contains at least one U (same shape for L, D, S)", password.LEGEND),
}


def render():
    dot = shutil.which("dot")
    for name, text in DIAGRAMS.items():
        (OUT / f"{name}.dot").write_text(text, encoding="utf-8")
        if dot:
            subprocess.run([dot, "-Tpng", "-Gdpi=130", str(OUT / f"{name}.dot"), "-o", str(OUT / f"{name}.png")], check=True)
            subprocess.run([dot, "-Tsvg", str(OUT / f"{name}.dot"), "-o", str(OUT / f"{name}.svg")], check=True)
    print(f"wrote {len(DIAGRAMS)} diagrams to {OUT}" + ("" if dot else "  (Graphviz not found: DOT only)"))


def stats():
    a, b = password.PASSWORD_DFA_A, password.PASSWORD_DFA_B
    md = ["# Design statistics (generated by tools/generate_diagrams.py)\n"]
    md.append("## State counts\n")
    md.append("| Machine | States | Note |\n|---|---|---|")
    md.append(f"| ATM PIN DFA | {len(pin.PIN_DFA.states)} | q0..q4 + dead; already minimal |")
    md.append(f"| ATM retry limiter | {len(pin.RETRY_DFA.states)} | fail0, fail1, fail2, AUTH, LOCKED |")
    md.append(f"| E-mail NFA | {len(email.EMAIL_NFA.states)} | hand-built, no ε-moves |")
    md.append(f"| E-mail DFA (subset construction) | {len(email.EMAIL_DFA_RAW.states)} | includes the dead state |")
    md.append(f"| E-mail DFA (minimal) | {len(email.EMAIL_DFA.states)} | one state merged |")
    md.append(f"| Password design A (direct) | {len(a.states)} | state = (length, classes seen) + dead |")
    md.append(f"| Password design B (product of 6 rule DFAs) | {len(b.states)} | reachable product states |")
    md.append(f"| Password A minimised | {len(password.PASSWORD_DFA.states)} | |")
    md.append(f"| Password B minimised | {len(b.minimize().states)} | identical to A minimised |")
    md.append(f"| Mini password policy (for the diagram) | {len(password.MINI_DFA.states)} | |")
    md.append("")
    md.append(f"A and B equivalence check (shortest distinguishing string): `{a.counterexample(b)}`\n")
    md.append("## ATM PIN DFA transition table\n")
    md.append(pin.PIN_DFA.transition_table_md())
    md.append("## ATM retry limiter transition table\n")
    md.append(pin.RETRY_DFA.transition_table_md())
    md.append("## E-mail NFA transition table\n")
    md.append(email.EMAIL_NFA.transition_table_md())
    md.append("## E-mail DFA by subset construction (state = set of NFA states)\n")
    md.append(email.EMAIL_DFA_RAW.transition_table_md())
    md.append("## E-mail DFA, minimal\n")
    md.append(email.EMAIL_DFA.transition_table_md())
    md.append("## Mini password DFA transition table\n")
    md.append(password.MINI_DFA.transition_table_md())
    (DOCS / "design_stats.md").write_text("\n".join(md), encoding="utf-8")
    print(f"wrote {DOCS / 'design_stats.md'}")


if __name__ == "__main__":
    render()
    stats()
